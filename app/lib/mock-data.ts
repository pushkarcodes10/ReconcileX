const generateTransactions = (count: number): Transaction[] => {
  const sources: DataSourceType[] = ["BANK", "PAYMENT_GATEWAY", "INTERNAL_ORDERS", "ACCOUNTING"];
  const statuses: Transaction["status"][] = ["MATCHED", "POTENTIAL_MATCH", "UNMATCHED", "EXCEPTION", "RESOLVED"];
  const currencies = ["INR", "USD", "EUR"];
  const transactions: Transaction[] = [];

  for (let i = 0; i < count; i++) {
    const source = sources[Math.floor(Math.random() * sources.length)];
    const status = statuses[Math.floor(Math.random() * statuses.length)];
    const baseAmount = Math.floor(Math.random() * 50000) + 100;
    const amount = baseAmount + Math.random() * 99.99;

    transactions.push({
      id: `TXN-${String(100000 + i).padStart(6, "0")}`,
      externalId: `EXT-${source.slice(0, 3).toUpperCase()}-${String(200000 + i).padStart(6, "0")}`,
      source,
      amount: Math.round(amount * 100) / 100,
      currency: currencies[Math.floor(Math.random() * currencies.length)],
      date: new Date(Date.now() - Math.floor(Math.random() * 30) * 24 * 60 * 60 * 1000).toISOString().split("T")[0],
      status,
      matchConfidence: status === "MATCHED" ? 100 : status === "POTENTIAL_MATCH" ? 60 + Math.floor(Math.random() * 30) : undefined,
      matchReason: status === "MATCHED" ? "Exact reference + amount match" : status === "POTENTIAL_MATCH" ? "Amount match, date within tolerance" : undefined,
      reconciliationRunId: `RUN-${20260915 - Math.floor(Math.random() * 30)}-${String(Math.floor(Math.random() * 10)).padStart(3, "0")}`,
      createdAt: new Date(Date.now() - Math.floor(Math.random() * 60) * 24 * 60 * 60 * 1000).toISOString(),
      updatedAt: new Date(Date.now() - Math.floor(Math.random() * 30) * 24 * 60 * 60 * 1000).toISOString(),
    });
  }

  return transactions;
};

